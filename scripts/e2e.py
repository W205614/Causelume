"""Run one isolated checkout incident through the public APIs of a running stack."""
import argparse
import http.cookiejar
import json
import os
import time
import uuid
from pathlib import Path
from datetime import datetime, timezone
from urllib import error, request


class Client:
    def __init__(self, base):
        self.base = base.rstrip("/")
        self.opener = request.build_opener(request.HTTPCookieProcessor(http.cookiejar.CookieJar()))

    def call(self, path, body=None, expected=(200, 201, 202, 204), token=None):
        headers = {"Accept": "application/json"}
        data = None
        if body is not None:
            data = json.dumps(body).encode()
            headers["Content-Type"] = "application/json"
        if token:
            headers["Authorization"] = "Bearer " + token
        req = request.Request(self.base + path, data=data, headers=headers)
        try:
            response = self.opener.open(req, timeout=45)
        except error.HTTPError as exc:
            response = exc
        with response:
            raw = response.read()
            if response.status not in expected:
                raise RuntimeError(f"{path} returned {response.status}: {raw[:400]!r}")
            return json.loads(raw) if raw else None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--expect-mode", choices=["offline", "holmes"], default="offline")
    parser.add_argument("--app", default="http://127.0.0.1:18760")
    parser.add_argument("--checkout", default="http://127.0.0.1:18761")
    parser.add_argument("--env-file", type=Path, help="read local demo credentials generated by init_env.py")
    args = parser.parse_args()
    credentials = {}
    if args.env_file:
        for line in args.env_file.read_text(encoding="utf-8").splitlines():
            key, sep, value = line.partition("=")
            if key == "AGENT_MODE" and value != args.expect_mode:
                parser.error(f"Configured AGENT_MODE={value}, expected {args.expect_mode}. Check the mode before running.")
            if sep and key in {"APP_ADMIN_PASSWORD", "APP_OPERATOR_PASSWORD", "DEMO_CONTROL_TOKEN"}:
                credentials[key] = value
    credentials.update(os.environ)
    api, checkout = Client(args.app), Client(args.checkout)
    token = credentials["DEMO_CONTROL_TOKEN"]
    api.call("/api/login", {"username": "admin", "password": credentials["APP_ADMIN_PASSWORD"]})
    services = api.call("/api/services")
    service = next(s for s in services if s["name"] == "checkout")
    operator = next(u for u in api.call("/api/users") if u["username"] == "operator")
    unique = str(uuid.uuid4())
    checkout.call("/control", {"fault": True}, token=token)
    try:
        checkout.call("/checkout", expected=(503,))
        metrics = api.call(f"/api/services/{service['id']}/metrics")
        logs = api.call(f"/api/services/{service['id']}/logs")
        assert metrics["errors"] > 0 and any(row["status"] == 503 for row in logs["entries"])
        alert_input = dict(serviceId=service["id"], source="checkout-e2e", externalId=unique,
                           title="结算请求返回 503", severity="CRITICAL",
                           occurredAt=datetime.now(timezone.utc).isoformat())
        alert = api.call("/api/alerts", alert_input)
        assert api.call("/api/alerts", alert_input)["id"] == alert["id"]
        ticket_input = dict(serviceId=service["id"], title="调查结算失败", alertId=alert["id"], requestId=unique)
        ticket = api.call("/api/tickets", ticket_input)
        assert api.call("/api/tickets", ticket_input)["id"] == ticket["id"]
        path = f"/api/tickets/{ticket['id']}"

        def action(name, note, **fields):
            version = api.call(path)["version"]
            return api.call(path + "/actions", dict(version=version, action=name, note=note, **fields))

        action("ASSIGN", "派给值班运维", assigneeId=operator["id"])
        api.call("/api/login", {"username": "operator", "password": credentials["APP_OPERATOR_PASSWORD"]})
        action("START", "已复现 HTTP 503")
        task = api.call("/api/tasks", {"ticketId": ticket["id"], "requestId": str(uuid.uuid4())})
        deadline = time.monotonic() + 115
        while task["status"] in ("PENDING", "QUEUED", "RUNNING") and time.monotonic() < deadline:
            time.sleep(.5)
            task = api.call(f"/api/tasks/{task['id']}")
        assert task["status"] == "SUCCEEDED", (task["status"], task.get("error"))
        assert task["mode"] == args.expect_mode, task["mode"]
        evidence = task["result"]["evidence"]
        assert {e["source"] for e in evidence} >= {"checkout:/metrics", "checkout:/logs"}, evidence
        api.call(f"/api/tasks/{task['id']}/feedback", {"feedback": "验收脚本已核对日志与指标"})
        action("NOTE", "验收脚本代行负责人步骤：确认故障并开始恢复")
    finally:
        checkout.call("/control", {"fault": False}, token=token)
    checkout.call("/checkout", expected=(200,))
    action("VERIFY", "已请求 /checkout 并验证 HTTP 200")
    action("CLOSE", "复盘：受控故障导致 503；恢复后实测 200，补充结算探测")
    assert api.call(path)["status"] == "CLOSED"
    print(f"Passed: alert {alert['id']}, ticket {ticket['id']}, task {task['id']}, {task['mode']} investigation; HTTP 503 -> 200")


if __name__ == "__main__":
    main()
