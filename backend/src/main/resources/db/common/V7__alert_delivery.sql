CREATE TABLE notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_id BIGINT NOT NULL REFERENCES accounts, ticket_id BIGINT REFERENCES tickets,
 event_type VARCHAR(32) NOT NULL, message VARCHAR(500) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL, read_at TIMESTAMP WITH TIME ZONE,
 mail_to VARCHAR(254), mail_status VARCHAR(16) NOT NULL, attempts INTEGER DEFAULT 0 NOT NULL,
 next_attempt TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL, last_error VARCHAR(100),
 claimed_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX notifications_by_recipient ON notifications(recipient_id,id);
CREATE INDEX notifications_ready ON notifications(mail_status,next_attempt,id);
CREATE TABLE mail_resends (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, notification_id BIGINT NOT NULL REFERENCES notifications,
 actor VARCHAR(64) NOT NULL, reason VARCHAR(500) NOT NULL, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
