CREATE TABLE tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES tickets,
 creator_id BIGINT NOT NULL REFERENCES accounts,
 request_id UUID NOT NULL,
 status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING','RUNNING','SUCCEEDED','FAILED')),
 mode VARCHAR(16), analysis CHARACTER VARYING, error VARCHAR(1000), feedback VARCHAR(2000),
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 UNIQUE(creator_id,request_id)
);
CREATE INDEX tasks_by_status ON tasks(status,id);
