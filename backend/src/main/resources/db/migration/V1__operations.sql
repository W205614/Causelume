CREATE TABLE alerts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, service_id BIGINT NOT NULL REFERENCES services,
 source VARCHAR(100) NOT NULL, external_id VARCHAR(200) NOT NULL, severity VARCHAR(16) NOT NULL,
 title VARCHAR(200) NOT NULL, occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(service_id,source,external_id)
);
CREATE TABLE tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, service_id BIGINT NOT NULL REFERENCES services,
 alert_id BIGINT UNIQUE REFERENCES alerts, title VARCHAR(200) NOT NULL, status VARCHAR(16) NOT NULL,
 assignee_id BIGINT REFERENCES accounts, version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 review VARCHAR(2000), creator_id BIGINT NOT NULL REFERENCES accounts, request_id UUID NOT NULL, UNIQUE(creator_id,request_id)
);
CREATE TABLE timeline (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL REFERENCES tickets,
 action VARCHAR(16) NOT NULL, note VARCHAR(2000) NOT NULL, actor VARCHAR(64) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor VARCHAR(64) NOT NULL, action VARCHAR(32) NOT NULL,
 target_id BIGINT NOT NULL, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
