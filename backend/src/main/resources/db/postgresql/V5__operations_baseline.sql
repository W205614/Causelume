CREATE TABLE accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(64) UNIQUE NOT NULL, password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(16) NOT NULL CHECK (role IN ('ADMIN','OPERATOR'))
);
CREATE TABLE services (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) UNIQUE NOT NULL, description VARCHAR(500) NOT NULL, resource VARCHAR(200) NOT NULL
);
